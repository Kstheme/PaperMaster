export function translate(language, key, vars) {
  const pack = copy[language] || copy.zh;
  const template = pack[key] ?? copy.zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

const LocaleContext = createContext({ language: 'zh', t: (key, vars) => translate('zh', key, vars) });

export function LocaleProvider({ language, children }) {
  const value = useMemo(() => ({ language, t: (key, vars) => translate(language, key, vars) }), [language]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}
